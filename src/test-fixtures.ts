export function createSeededStorage(data: Data = sampleSeedData): MemoryStorage {
  const storage = new MemoryStorage();
  storage.setItem('rodrigo-crm', JSON.stringify(structuredClone(data)));
  return storage;
}

export function createSeededRepository(data: Data = sampleSeedData): {
  storage: MemoryStorage;
  repo: JsonRepository;
} {
  const storage = createSeededStorage(data);
  return { storage, repo: new JsonRepository(storage) };
}
